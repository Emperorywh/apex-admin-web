/**
 * 五语 → 表格文案包的唯一映射表；key 即 AppLanguage 值集（T016 合同）。
 * 简中键直接引用库内 zhCN，保证与库版本随行更新。
 */
export const APEX_TABLE_LOCALES: Record<AppLanguage, ApexLocale> = {
  'zh-CN': zhCN,
  'en-US': enUS,
  'zh-TW': zhTW,
  'ja-JP': jaJP,
  'ko-KR': koKR,
}

/** 按归一化后的应用语言取表格文案包；未知语言已在 normalizeLanguage 兜底为简中 */
export function resolveApexTableLocale(language: AppLanguage): ApexLocale {
  return APEX_TABLE_LOCALES[language]
}
